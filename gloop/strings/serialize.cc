// Helper functions for KeyFromDouble/KeyToDouble and KeyFromFloat/KeyToFloat.
namespace {
// Encodes the given IEEE-754 floating-point argument in the specified unsigned
// integer type.  E.g., uint64 x = UintFromIEEE754<uint64>(my_double);
// IEEE standard 754 floating point representation
//   [sign-bit] [exponent] [mantissa]
//
// Let "a", "b" be two double values, and F(.) be following
// transformation.  We have:
//   If 0 < a < b:
//     0x80000000ULL < uint64(F(a)) < uint64(F(b))
//   If a == -0.0, b == +0.0:
//     uint64(F(-0.0)) == uint64(F(+0.0)) = 0x80000000ULL
//   If a < b < 0:
//     uint64(F(a)) < uint64(F(b)) < 0x80000000ULL
template <typename UintType, typename FloatType>
UintType UintFromIEEE754(FloatType f) {
  const UintType n = absl::bit_cast<UintType>(f);
  const UintType sign_bit = ~(~static_cast<UintType>(0) >> 1);
  if ((n & sign_bit) == 0) return n + sign_bit;
  return 0 - n;
}

// Encodes the given unsigned integer argument in the specified IEEE-754
// floating-point format.  E.g., double x = IEEE754FromUint<double>(my_uint64);
// Inverse of above.
template <typename FloatType, typename UintType>
FloatType IEEE754FromUint(UintType n) {
  const UintType sign_bit = ~(~static_cast<UintType>(0) >> 1);
  if (n & sign_bit) {
    n -= sign_bit;
  } else {
    n = 0 - n;
  }
  return absl::bit_cast<FloatType>(n);
}
}  // namespace

// Converts a double value to an 8-byte string key, so that the string keys sort
// in the same order as the original double values.
// -0.0 and +0.0 convert to the same key.
void KeyFromDouble(double x, std::string* key) {
  const uint64_t n = UintFromIEEE754<uint64_t>(x);
  *key = Uint64ToKey(n);
}

// Version of KeyFromDouble that returns the key.
std::string DoubleToKey(double x) {
  std::string key;
  KeyFromDouble(x, &key);
  return key;
}

// Converts key generated by KeyFromDouble() back to double.
double KeyToDouble(absl::string_view key) {
  const uint64_t n = KeyToUint64(key);
  return IEEE754FromUint<double>(n);
}

// Converts a float value to a 4-byte string key, so that the string keys sort
// in the same order as the original float values.
// -0.0 and +0.0 convert to the same key.
void KeyFromFloat(float x, std::string* key) {
  const uint32_t n = UintFromIEEE754<uint32_t>(x);
  *key = Uint32ToKey(n);
}

// Version of KeyFromFloat that returns the key.
std::string FloatToKey(float x) {
  std::string key;
  KeyFromFloat(x, &key);
  return key;
}

// Converts key generated by FloatToKey() back to float.
float KeyToFloat(absl::string_view key) {
  const uint32_t n = KeyToUint32(key);
  return IEEE754FromUint<float>(n);
}

// Converts int32 to a 4-byte string key such that lexicographic
// ordering of strings is equivalent to sorting in increasing order by
// integer values. This can be useful when constructing secondary
// keys for mapreduce jobs.
std::string Int32ToOrderedString(int32_t i32) {
  uint32_t ui32 = static_cast<uint32_t>(i32) ^ 0x80000000;
  return Uint32ToKey(ui32);
}

// The inverse of the above function.
int32_t OrderedStringToInt32(absl::string_view key) {
  uint32_t ui32 = 0;
  CHECK_EQ(key.size(), sizeof(ui32));
  for (unsigned char character : key) {
    ui32 = (ui32 << 8);
    ui32 = ui32 | character;
  }
  return static_cast<int32_t>(ui32 ^ 0x80000000);
}

// Converts int64 to a 8-byte string key such that lexicographic
// ordering of strings is equivalent to sorting in increasing order by
// integer values.
std::string Int64ToOrderedString(int64_t i64) {
  uint64_t ui64 = static_cast<uint64_t>(i64) ^ 0x8000000000000000;
  return Uint64ToKey(ui64);
}

// The inverse of the above function.
int64_t OrderedStringToInt64(absl::string_view key) {
  uint64_t ui64 = 0;
  CHECK_EQ(key.size(), sizeof(ui64));
  for (unsigned char character : key) {
    ui64 = (ui64 << 8);
    ui64 = ui64 | character;
  }
  return static_cast<int64_t>(ui64 ^ (uint64_t{1} << 63));
}

// Converts int32 to a 4-byte string key such that lexicographic
// ordering of strings is equivalent to sorting in decreasing order
// by integer values. This can be useful when constructing secondary
// keys for mapreduce jobs.
void ReverseOrderedStringFromInt32(int32_t i32, std::string* key) {
  // ~ is like -, but works even for INT_MIN. (-INT_MIN == INT_MIN,
  // but ~x = -x - 1, so ~INT_MIN = -INT_MIN - 1 = INT_MIN - 1 = INT_MAX).
  *key = Int32ToOrderedString(~i32);
}

std::string Int32ToReverseOrderedString(int32_t i32) {
  return Int32ToOrderedString(~i32);
}

// The inverse of the above function.
int32_t ReverseOrderedStringToInt32(absl::string_view key) {
  return ~OrderedStringToInt32(key);
}

// Converts int64 to an 8-byte string key such that lexicographic
// ordering of strings is equivalent to sorting in decreasing order
// by integer values. This can be useful when constructing secondary
// keys for mapreduce jobs.
void ReverseOrderedStringFromInt64(int64_t i64, std::string* key) {
  *key = Int64ToOrderedString(~i64);
}

std::string Int64ToReverseOrderedString(int64_t i64) {
  return Int64ToOrderedString(~i64);
}

// The inverse of the above function.
int64_t ReverseOrderedStringToInt64(absl::string_view key) {
  return ~OrderedStringToInt64(key);
}

bool DictionaryParse(
    absl::string_view encoded_str,
    absl::FunctionRef<void(absl::string_view, absl::string_view)> callback) {
  for (const absl::string_view entry :
       absl::StrSplit(encoded_str, ',', absl::SkipEmpty())) {
    const auto fields = absl::StrSplit(entry, ':');
    auto it = fields.begin();
    const auto end = fields.end();
    if (it == end) return false;
    const absl::string_view key = *it;
    if (++it == end) return false;
    const absl::string_view value = *it;
    if (++it != fields.end()) return false;
    callback(key, value);
  }
  return true;
}

bool DictionaryParse(absl::string_view encoded_str,
                     std::vector<std::pair<std::string, std::string>>* items) {
  return DictionaryParse(
      encoded_str, [items](absl::string_view key, absl::string_view value) {
        items->emplace_back(key, value);
      });
}

