#include "gloop/base/internal/percpu.inc"

.section google_malloc, "ax"

// Each rseq function defined below should have this general form:
//
//     START_FUNCTION(FunctionName)
//
//       [...]  // Critical section
//
//     .LFunctionName_critical_limit
//       [...]
//       ret  // Return to user
//
//     END_FUNCTION(FunctionName)
//
// If interrupted during the critical section, the function will be restarted
// from just after the START_FUNCTION macro.
//
// General-purpose register allocations (refer to Procedure Call Standard for
// the ARM 64-bit Architecture):
//
//  *  r0 is defined by the ABI to contain the first input parameter and return
//     value. The abort handler assumes that the first input parameter is a
//     pointer to __rseq_abi, and rseq functions must preserve this invariant
//     throughout their critical section.
//
//  *  r1-r7 are defined by the ABI to contain subsequent input parameters and
//     return values. An rseq function is free to do with these as it likes,
//     and they are not modified by the abort handler. (Of course if an
//     argument is overwritten, its original value will not be restored when
//     restarting.)
//
//  *  r8 is defined by the ABI to contain the address of the result of the
//     function when it isn't returned by register, upon entry to the function.
//     This is not relevant to any of the functions defined here, and it can be
//     used freely. The abort handler will not modify it.
//
//  *  r9-r15 are defined by the ABI to be for temporary use by callees. The
//     abort handler makes no claims to these, and they can be used freely.
//
//  *  r16-r17 are defined by the ABI to be the intra-procedure-call temporary
//     registers, used by the linker when it needs to insert a call veneer.
//     Outside of branch instructions that may be exposed to long relocations
//     these can be used freely, so this is not relevant here.
//
//     The abort handler reserves the right to overwrite r17, but otherwise
//     these two registers can be used by rseq functions.
//
//  *  r18 is defined by the ABI to be a platform-specific register, and it
//     advises steering clear of it in hand-written assembly.
//
//  *  r19-r28 are defined by the ABI to be callee-saved registers. In theory
//     rseq functions could use these as long as they restored them afterward,
//     but there are plenty of other registers available.
//
//  *  r30 is the link register, used to store the return value when executing
//     a branch instruction.
//
//  *  r31 is an alias for the stack pointer or zero register, depending on
//     context.
//

////////////////////////////////////////////////////////////////////////
// Macros
////////////////////////////////////////////////////////////////////////

// Place the current CPU number into dst, which must be a 32-bit register.
#define GET_CPU(dst) \
    ldr dst, [x0, 4]

// Given a CPU number, calculate the offset of that CPU's word from CPU 0's
// into dst.
#define CALCULATE_PER_CPU_WORD_OFFSET(dst, cpu) \
    lsl dst, cpu, PERCPU_BYTES_PER_REGION_SHIFT

#ifdef __ARM_FEATURE_BTI_DEFAULT
#define GNU_PROPERTY_AARCH64_BTI 1  // Has Branch Target Identification
#define AARCH64_VALID_CALL_TARGET hint #34  // BTI c
#else
#define GNU_PROPERTY_AARCH64_BTI 0  // No Branch Target Identification
#define AARCH64_VALID_CALL_TARGET
#endif

// START_FUNCTION(FunctionName) expands to approximately the following:
//
//     <abort handler signature>
//     FunctionName:
//       store function's rseq_cs to __rseq_abi.rseq_cs
//     FunctionName_start:
//
// Setting __rseq_abi.rseq_cs (to the address of the struct generated by
// END_FUNCTION) informs the kernel we're in a restartable sequence. We do this
// both on entry to the function and after being aborted, because the kernel
// clears it on abort.
#define START_FUNCTION(label)                                         \
  /*                                                                  \
   * Include the signature that must precede the abort handler in the \
   * linux rseq ABI, since rseq_cs could live in an                   \
   * attacker-writeable segment.                                      \
   */                                                                 \
  .long PERCPU_RSEQ_SIGNATURE;                                        \
                                                                      \
label:                                                                \
  CFI(.cfi_startproc);                                                \
  AARCH64_VALID_CALL_TARGET;                                          \
  /*                                                                  \
   * Load the address of the rseq_cs struct for this function. We do  \
   * this by first loading the high bits, then adding the low 12      \
   * bits. See https://stackoverflow.com/a/38608738 and               \
   * https://stackoverflow.com/a/54042899.                            \
   */                                                                 \
  adrp x17, __rseq_cs_##label;                                        \
  add x17, x17, :lo12:__rseq_cs_##label;                              \
  str x17, [x0, 8];                                                   \
                                                                      \
  /* The critical section follows immediately. */                     \
  .L##label##_critical_start:

// END_FUNCTION(FunctionName) generates an rseq_cs table (the triple of
// start, commit, abort IPs) for FunctionName. This is stored outside of the
// section of the main implementation, and is referenced by START_FUNCTION.
#define END_FUNCTION(label)                                             \
  CFI(.cfi_endproc);                                                    \
                                                                        \
  /* Encode the size of the function, ensuring that tools know how to   \
   * display it properly. See cl/220751648. */                          \
  .size label, . - label;                                               \
                                                                        \
  /*                                                                    \
   * Define the rseq_cs struct for this critical section, putting it in \
   * the __rseq_cs segment as expected by tools like debuggers.         \
   */                                                                   \
  .pushsection __rseq_cs, "aw";                                         \
  .balign 32;                                                           \
  .protected __rseq_cs_##label;                                         \
  .type __rseq_cs_##label,@object;                                      \
  .size __rseq_cs_##label,32;                                           \
  __rseq_cs_##label:                                                    \
  .long PERCPU_RSEQ_VERSION, PERCPU_RSEQ_FLAGS;                         \
  .quad .L##label##_critical_start;                                     \
  .quad .L##label##_critical_limit - .L##label##_critical_start;        \
  .quad label;                                                          \
                                                                        \
  /*                                                                    \
   * Include a no-op reference to the __rseq_cs_ptr_array entry for     \
   * the function we're describing (defined below). Because the present \
   * section is referenced by the .text section, this will prevent the  \
   * linker from garbage collecting the __rseq_cs_ptr_array section.    \
   */                                                                   \
  .reloc 0, R_AARCH64_NONE, .L##label##array;                           \
  .popsection;                                                          \
                                                                        \
  /*                                                                    \
   * Add an entry for this function's rseq_cs struct to the             \
   * __rseq_cs_ptr_array section. This may be used by debuggers and     \
   * other dynamic tools to give a better experience when dealing with  \
   * rseq functions. See discussion at					\
   * https://github.com/DynamoRIO/dynamorio/issues/2350#issuecomment-500243144 \
   * and in cl/355113877.                    \
   */                                                                   \
  .pushsection __rseq_cs_ptr_array, "aw";                               \
  .L##label##array:                                                     \
  .quad __rseq_cs_##label;                                              \
  .popsection

////////////////////////////////////////////////////////////////////////
// RseqFunction_PerCpuAtomicFetchAdd
////////////////////////////////////////////////////////////////////////

.globl RseqFunction_PerCpuAtomicFetchAdd
.type  RseqFunction_PerCpuAtomicFetchAdd, @function
START_FUNCTION(RseqFunction_PerCpuAtomicFetchAdd)
  // Register use:
  //
  //  *  r0: (Argument: kernel_rseq*) rseq_abi
  //  *  r1: (Argument: Handle) h
  //  *  r2: (Argument: int64_t) delta
  //  *  r3: Current CPU number.
  //  *  r4: This CPU's word's offset from CPU 0's.
  //  *  r5: Current value of the word.
  //  *  r6: New value of the word.
  //

  // Fetch the current CPU number and calculate the offset of its data from CPU
  // zero's data.
  GET_CPU(w3)
  CALCULATE_PER_CPU_WORD_OFFSET(x4, x3)

  // Read the current value of the word and add the delta.
  ldr x5, [x1, x4]
  add x6, x5, x2

  // Write out the word, committing the operation.
  str x6, [x1, x4]
.LRseqFunction_PerCpuAtomicFetchAdd_critical_limit:

  // Return a (CPU number, previous value) pair.
  mov x0, x3
  mov x1, x5
  ret

END_FUNCTION(RseqFunction_PerCpuAtomicFetchAdd);

////////////////////////////////////////////////////////////////////////
// RseqFunction_PerCpuCmpxchg64
////////////////////////////////////////////////////////////////////////

.globl RseqFunction_PerCpuCmpxchg64
.type  RseqFunction_PerCpuCmpxchg64, @function
START_FUNCTION(RseqFunction_PerCpuCmpxchg64)
  // Register use:
  //
  //  *  r0: (Argument: kernel_rseq*) rseq_abi
  //  *  r1: (Argument: int64) target_cpu
  //  *  r2: (Argument: int64_t*) p
  //  *  r3: (Argument: int64_t) old_val
  //  *  r4: (Argument: int64_t) new_val
  //  *  r5: The current CPU number.
  //  *  r6: The current value of *p.
  //

  // Are we running on the target CPU?
  GET_CPU(w5)
  cmp x5, x1
  b.ne .LRseqFunction_PerCpuCmpxchg64_wrong_cpu

  // Load the current value of *p.
  ldr x6, [x2]

  // Is the value up to date?
  cmp x6, x3
  b.ne .LRseqFunction_PerCpuCmpxchg64_wrong_value

  // Store the new value, committing the operation.
  str x4, [x2]
.LRseqFunction_PerCpuCmpxchg64_critical_limit:

.LRseqFunction_PerCpuCmpxchg64_wrong_cpu:
  // Return the current CPU number (which is also the target CPU number if we
  // fell through to here from the success path).
  mov x0, x5
  ret

.LRseqFunction_PerCpuCmpxchg64_wrong_value:
  // Return -1.
  mov x0, -1
  ret

END_FUNCTION(RseqFunction_PerCpuCmpxchg64);

////////////////////////////////////////////////////////////////////////
// RseqFunction_PerCpuCmpxchgCheck64
////////////////////////////////////////////////////////////////////////

.globl RseqFunction_PerCpuCmpxchgCheck64
.type  RseqFunction_PerCpuCmpxchgCheck64, @function
START_FUNCTION(RseqFunction_PerCpuCmpxchgCheck64)
  // Register use:
  //
  //  *  r0: (Argument: kernel_rseq*) rseq_abi
  //  *  r1: (Argument: int64) target_cpu
  //  *  r2: (Argument: int64_t*) p
  //  *  r3: (Argument: int64_t) old_val
  //  *  r4: (Argument: int64_t) new_val
  //  *  r5: (Argument: int64_t*) check_ptr
  //  *  r6: (Argument: int64_t) check_val
  //  *  r7: The current CPU number.
  //  *  r8: The current value of *p.
  //  *  r9: The current value of *check_ptr.
  //

  // Are we running on the target CPU?
  GET_CPU(w7)
  cmp x7, x1
  b.ne .LRseqFunction_PerCpuCmpxchgCheck64_wrong_cpu

  // Load the current values of *p and *check_ptr.
  ldr x8, [x2]
  ldr x9, [x5]

  // Are they both up to date?
  cmp x8, x3
  ccmp x9, x6, 0 /* clear Z bit -> ne */, eq
  b.ne .LRseqFunction_PerCpuCmpxchgCheck64_wrong_value

  // Store the new value, committing the operation.
  str x4, [x2]
.LRseqFunction_PerCpuCmpxchgCheck64_critical_limit:

.LRseqFunction_PerCpuCmpxchgCheck64_wrong_cpu:
  // Return the current CPU number (which is also the target CPU number if we
  // fell through to here from the success path).
  mov x0, x7
  ret

.LRseqFunction_PerCpuCmpxchgCheck64_wrong_value:
  // Return -1.
  mov x0, -1
  ret

END_FUNCTION(RseqFunction_PerCpuCmpxchgCheck64);

////////////////////////////////////////////////////////////////////////
// RseqFunction_PerCpuReadCycleCounter
////////////////////////////////////////////////////////////////////////

.globl RseqFunction_PerCpuReadCycleCounter
.type  RseqFunction_PerCpuReadCycleCounter, @function
START_FUNCTION(RseqFunction_PerCpuReadCycleCounter)
  // Register use:
  //
  //  *  r0: (Argument: kernel_rseq*) rseq_abi
  //  *  r1: The cycle count for the current CPU.
  //  *  r2: The current CPU number.
  //

  // Load the current CPU number and that CPU's cycle count.
  GET_CPU(w2)
  mrs x1, pmccntr_el0
.LRseqFunction_PerCpuReadCycleCounter_critical_limit:

  // Return a (CPU number, cycle count) pair.
  mov x0, x2
  ret

END_FUNCTION(RseqFunction_PerCpuReadCycleCounter);

////////////////////////////////////////////////////////////////////////
// RseqFunction_PerCpuTryLock
////////////////////////////////////////////////////////////////////////

.globl RseqFunction_PerCpuTryLock
.type  RseqFunction_PerCpuTryLock, @function
START_FUNCTION(RseqFunction_PerCpuTryLock)
  // Register use:
  //
  //  *  r0: (Argument: kernel_rseq*) rseq_abi
  //  *  r1: (Argument: int64_t*) cpu_0_lock_word
  //  *  r2: (Argument: int64_t) New value of lock word.
  //  *  r3: Current CPU number.
  //  *  r4: Offset of current CPU's lock word from CPU 0's.
  //  *  r5: Current value of lock word.
  //

  // Fetch the current CPU number and calculate the offset of its data from CPU
  // zero's data.
  GET_CPU(w3)
  CALCULATE_PER_CPU_WORD_OFFSET(x4, x3)

#ifdef __ARM_FEATURE_RCPC
  // Check whether the lock word is zero. If not, it is currently held. Note
  // that we need to do a load-aquire to read the lock word in order to
  // synchronize with the store-release in the Unlock function, ensuring
  // that writes made in the last critical section are visible to the critical
  // section we're currently entering.
  add x6, x1, x4
  ldapr x5, [x6]
  cbnz x5, .LRseqFunction_PerCpuTryLock_already_locked
  // Store the new value, committing the operation.
  str x2, [x6]
#else
  // Check whether the lock word is zero. If not, it is currently held.
  ldr x5, [x1, x4]
  cbnz x5, .LRseqFunction_PerCpuTryLock_already_locked

  // Store the new value, committing the operation.
  str x2, [x1, x4]
#endif

.LRseqFunction_PerCpuTryLock_critical_limit:

  // Return the CPU number.
  mov x0, x3
  ret

.LRseqFunction_PerCpuTryLock_already_locked:
  // Return -1 to indicate the lock was already held.
  mov x0, -1
  ret

END_FUNCTION(RseqFunction_PerCpuTryLock);

