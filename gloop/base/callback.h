// NOTE: Google's internal Callback and Closure classes should not be used
// in new code; they remain purely for interoperability with existing code at
// this point, and that code is being refactored to eliminate their usage.
// Prefer lambda expressions, `absl::FunctionRef`, `absl::AnyInvocable`, and
// (on occasion) C++11's standard `std::function`.
// See <link>.
//
// Callback classes provide a generic interface for classes requiring
// callback from other classes. See the following codelab for details:
// <link>
//
// We support callbacks with multiple arguments.
//   Closure                  -- provides "void Run()"
//   Callback1<T1>            -- provides "void Run(T1)"
//   Callback2<T1,T2>         -- provides "void Run(T1, T2)"
//   ResultCallback1<R,T1>    -- provides "R Run(T1)"
//   ...
//
// Arguments can be pre-bound; see the Examples section below for examples.
//
// Callbacks are created from function objects via util::functional::ToCallback
// and util::functional::ToPermanentCallback functions. ToCallback creates a
// self-destructing callback that can _only_ be called once, while
// ToPermanentCallback creates a callback that must be deleted explicitly.
// You MUST use ToPermanentCallback if you're planning on using a callback more
// than once. The CheckIsRepeatable() method is provided in any callback to die
// if it is not permanent (aka repeatable).
//
// Context behavior: ToCallback captures the current thread-local
// base::Context, and that Context is installed while the callback runs.
// ToPermanentCallback does not capture the current Context, so the created
// callback runs with whatever Context is current when Run() is called.
//
// For more examples of how to use ToCallback and ToPermanentCallback, see
// util/functional/to_callback.h

