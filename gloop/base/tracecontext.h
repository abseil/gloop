// TraceContext defines the state carried around by all threads and
// non-permanent callbacks.
//
// This state identifies the RPC that a callback/thread is acting for,
// the causal parent RPC of the current RPC,
// the global distributed trace that this RPC is a part of,
// and the trace mask (indicating tracing options).
//
// The default RPC identifier is 0.
// The default parent RPC identifier is 0.
// The default Global identifier is 0.
// The default trace mask is 0 (off).
//
// Most uses of this interface will occur inside communication
// mechanisms, such as RPC systems.
//
// TraceContexts are stored in the current thread and certain kinds of
// callback.  For non-permanent callbacks created by NewCallback(),
// the TraceContext is automatically copied into the callback object
// when created, and the TraceContext is automatically swapped into
// the current thread inside the callback's Run method.
//
// All callbacks export a
//           TraceContext *trace_context_ptr()
// method that allows a client to change its internally stored
// TraceContext.  Changes via trace_context_ptr() are not thread-safe.
// You may not modify the contents of a callback's TraceContext except
// prior to running the callback.  It is especially dangerous to
// modify the contents of trace_context_ptr() while the callback is
// running.
//
// Note, callbacks generated by NewPermanentCallback() do not switch
// context.  User-defined callback classes (based on the abstract
// Closure or CallbackN) may access a protected trace_context_ member,
// but it is not initialized to the thread's TraceContext by default.
// To use TraceContext with user-defined callbacks, see callback.h.
//
// For an easy way to manage TraceContext propagation, see
// <path>
//
// Conceptually, on receiving an RPC packet (either call or return)
// that should be delivered to handler H->Handle(), the RPC system
// might do:
//    uint32_t mask = trace_mask_from_network_packet;
//    uint64_t rpc_id = RPC_ID_from_network_packet;
//    uint64_t parent_rpc_id = PARENT_RPC_ID_from_network_packet;
//    uint64_t global_id = GLOBAL_ID_from_network_packet;
//
//    TraceContext tc(TraceContext::kDefault);
//    tc.set_rpc_id(rpc_id);
//    tc.set_parent_rpc_id(parent_rpc_id);
//    tc.set_global_id(global_id);
//    tc.set_mask(mask);
//    tc.set_census_handle(census_handle_from_network_packet);
//
//    // Scope the over-the-wire context.
//    base::WithTraceContext with_tc(std::move(tc));
//
//    if (base::CurrentContext().trace()->CanRecordAnnotations()) {
//      ...log rpc_id arrival with time and other data according to
//         trace options
//    }
//
//    // This call to H->Handle() has the trace context received from
//    // the network.
//    H->Handle();
//
// When about to send an RPC packet (either call or return) for RPC
// with ID number new_rpc_id, the RPC system might do:
//    const TraceContext *tc = TraceContext::Current();
//    if (tc->is_traced()) {
//      uint64_t old_rpc_id = tc->rpc_id();
//      ... log old_rpc_id send with new_rpc_id, time, and other data ...;
//    }
//    ...copy mask into network packet...
//    ...send packet...
//

