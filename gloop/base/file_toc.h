#ifndef THIRD_PARTY_GLOOP_BASE_FILE_TOC_H_
#define THIRD_PARTY_GLOOP_BASE_FILE_TOC_H_

// This file defines the structure of the table-of-contents elements
// produced by cc_embed_data rules. Its canonical definition is
// base/file_toc.h, but a copy of it appears in each file generated by
// //tools:filewrapper.
//
// For information on how to use this class and API guarantees made by
// cc_embed_data rules, see:
// http://<path>

#include <stddef.h>

#ifdef __cplusplus
// Used by the filewrapper tool to allow use of `cc_embed_data` by C/ObjC.
// Use the `--c_linkage` flag to denote that "C" style linkage is desired.
// Note by default that C++ linkage is used. This option is incompatible with
// `--namespace`.
// cc_embed_data(
//     name = "some_data",
//     srcs = [
//         "a.png",
//     ],
//     outs = [
//         "some_data.cc",
//         "some_data.h",
//         "some_data.o",
//     ],
//     embedopts = ["--c_linkage"],
// )
#define BASE_FILE_TOC_EXTERN extern "C"
#else  // __cplusplus
#define BASE_FILE_TOC_EXTERN
#endif  // __cplusplus

struct FileToc {
  const char* name;
  const char* data;
  size_t size;
  unsigned char md5digest[16];
};

#endif  // THIRD_PARTY_GLOOP_BASE_FILE_TOC_H_
