// ----------------------------------------------------------------------
// main()
//    This is long mostly because we have lots of options.
// ----------------------------------------------------------------------

int main(int argc, char** argv) {
  InitGoogle(argv[0], &argc, &argv, true);

  if (absl::GetFlag(FLAGS_output).empty())
    LOG(FATAL) << "Must specify what kind of conversion you want via --output";
  CHECK(!absl::GetFlag(FLAGS_useglobaldb))
      << "Please use --use_global_db instead of --useglobaldb";

  google::protobuf::DescriptorPoolDatabase generated_db(
      *google::protobuf::DescriptorPool::generated_pool());
  google::protobuf::SimpleDescriptorDatabase descriptor_set_db;

  std::vector<google::protobuf::DescriptorDatabase*> descriptor_dbs;

  descriptor_dbs.push_back(&generated_db);

  // Now build a descriptor pool from either the parsed+generated protos,
  // or from the binary descriptor sets.
  google::protobuf::MergedDescriptorDatabase merged_descriptor_db(
      descriptor_dbs);
  google::protobuf::DescriptorPool merged_db(&merged_descriptor_db);

  LOG(INFO) << "Reading input from " << absl::GetFlag(FLAGS_input_filename);
  if (absl::GetFlag(FLAGS_output) == "protobuf" ||
      absl::GetFlag(FLAGS_output) == "json") {
    ::ReadAsciiProtoBuf(merged_db, absl::GetFlag(FLAGS_protoname),
                        absl::GetFlag(FLAGS_input_filename),
                        absl::GetFlag(FLAGS_output_filename),
                        absl::GetFlag(FLAGS_output));
  } else {
    LOG(FATAL) << "Unknown output conversion requested: "
               << absl::GetFlag(FLAGS_output);
  }

  LOG(INFO) << "DONE";
  return 0;
}
