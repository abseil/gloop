// ----------------------------------------------------------------------
// Convert()
// Write()
// WriteAs()
//    This templatized function wraps the stringstream we use to do
//    the actual conversion from a string to a simple type.  It
//    RETURNS true if we converted the entire input, false else,
//    and puts the converted value in ToType.
// ----------------------------------------------------------------------

template <typename ToType>
bool Convert(absl::string_view input, ToType* output, int base) {
  std::istringstream input_stream((std::string(input)));

  if (base == 8) {
    input_stream >> std::oct >> *output;
  } else if (base == 16) {
    input_stream >> std::hex >> *output;
  } else {
    input_stream >> *output;  // every other value taken as 10
  }
  if (input_stream.bad() || input_stream.fail()) {
    LOG(WARNING) << "Can't convert '" << input << "' to proper output type";
    return false;  // make sure we converted ok
  }

  // Try to read 1 extra character to make sure there's nothing left
  char c;
  input_stream >> c;
  if (!input_stream.eof()) {
    LOG(WARNING) << "'" << input << "' has extra chars at the end (" << c
                 << ")";
    return false;
  }

  return true;
}

// We specialize strings: no need to convert in that case!
template <>
bool Convert(absl::string_view input, std::string* output, int base) {
  output->assign(input);  // could be made more efficient, but whatever
  return true;
}

// ----------------------------------------------------------------------
// AbstractEncoder
//    This is an interface for encoding keys.
// ----------------------------------------------------------------------
class AbstractEncoder {
 public:
  virtual ~AbstractEncoder() {}

  // Encodes the key from the input file returns the result.
  // Returns false if input cannot be parsed.
  virtual bool Encode(const std::string& input, std::string* result) const = 0;
};

// AbstractEncoder used for all built-in types.
template <typename IntType>
class IntegerEncoder : public AbstractEncoder {
 public:
  virtual bool Encode(const std::string& input, std::string* result) const {
    IntType value;
    if (!Convert(input, &value, absl::GetFlag(FLAGS_key_base))) {
      return false;
    }
    *result = strings::EncodePOD(value);
    return true;
  }
};

// AbstractEncoder used for 'fp64'.
class Fp64Encoder : public AbstractEncoder {
 public:
  virtual bool Encode(const std::string& input, std::string* result) const {
    uint64_t value;
    if (!absl::SimpleAtoi(input, &value)) {
      return false;
    }
    *result = strings::Uint64ToKey(value);
    return true;
  }
};

// AbstractEncoder used for 'doublekey'.
class DoubleKeyEncoder : public AbstractEncoder {
 public:
  virtual bool Encode(const std::string& input, std::string* result) const {
    double value;
    if (!absl::SimpleAtod(input, &value)) {
      return false;
    }
    strings::KeyFromDouble(value, result);
    return true;
  }
};

// AbstractEncoder used for 'string'.
class StringEncoder : public AbstractEncoder {
 public:
  virtual bool Encode(const std::string& input, std::string* result) const {
    result->assign(input);
    return true;
  }
};

// AbstractEncoder used for protocol buffer encoding
class ProtoEncoder : public AbstractEncoder {
 public:
  ProtoEncoder(const std::string& pb_name,
               const google::protobuf::DescriptorPool& pool) {
    CHECK(!pb_name.empty());
    desc_ = pool.FindMessageTypeByName(pb_name);
    CHECK(desc_ != nullptr) << "Failed to find proto type [" << pb_name << "]";
  }
  virtual bool Encode(const std::string& input, std::string* result) const {
    google::protobuf::DynamicMessageFactory dynamic_message_factory;
    google::protobuf::Message* instance =
        dynamic_message_factory.GetPrototype(desc_)->New();
    CHECK(google::protobuf::TextFormat::ParseFromString(input, instance))
        << "Failed to parse ASCII [" << input << "]";

    std::string local_result;
    {
      // Use a nested block to guarantee triggering coded_stream's destructor
      // before `result` is used. Due to copy elision, this code works without
      // the nested block, but small, innocent looking changes can break it.
      // See <link> for more details.
      google::protobuf::io::StringOutputStream string_stream(&local_result);
      google::protobuf::io::CodedOutputStream coded_stream(&string_stream);
      coded_stream.SetSerializationDeterministic(true);
      CHECK(instance->SerializeToCodedStream(&coded_stream))
          << "Failed to serialize message to coded stream";
    }
    *result = std::move(local_result);

    delete instance;
    return true;
  }

 protected:
  const google::protobuf::Descriptor* desc_;
};

// AbstractEncoder used for string unscaping
class UnescapeEncoder : public AbstractEncoder {
 public:
  virtual bool Encode(const std::string& input, std::string* result) const {
    strings::UnescapeCEscapeString(input, result);
    return true;
  }
};

// Given a ProtocolDB, reads an ASCII representation of protocol
// buffer proto_name from file input_filename and writes the binary
// or jspb representation to a file called output_filename.  If unsucessful,
// this function logs a warning and returns.
void ReadAsciiProtoBuf(const google::protobuf::DescriptorPool& pool,
                       const std::string& proto_name,
                       const std::string& input_filename,
                       absl::string_view output_filename,
                       absl::string_view output_format) {
  std::ifstream file(input_filename, std::ios::in | std::ios::binary);
  if (!file) {
    LOG(FATAL) << "Failed to open input file [" << input_filename << "]";
  }
  std::string ascii_message((std::istreambuf_iterator<char>(file)),
                            std::istreambuf_iterator<char>());

  if (ascii_message.empty()) {
    LOG(WARNING) << "Input was empty; proceeding anyway";
  }

  const google::protobuf::Descriptor* descriptor =
      pool.FindMessageTypeByName(proto_name);
  CHECK(descriptor) << "Failed to find proto type [" << proto_name << "]";

  google::protobuf::DynamicMessageFactory message_factory;
  const google::protobuf::Message* prototype =
      message_factory.GetPrototype(descriptor);
  CHECK(prototype) << "Couldn't get prototype message.";

  std::unique_ptr<google::protobuf::Message> message(prototype->New());
  google::protobuf::TextFormat::Parser parser;
  google::protobuf::io::ArrayInputStream asciipb_istream(ascii_message.data(),
                                                         ascii_message.size());
  CHECK(parser.Parse(&asciipb_istream, message.get()))
      << "Failed to parse text format proto buffer from input file "
      << input_filename;

  if (output_format == "json") {
    std::string json_data;
    google::protobuf::util::JsonPrintOptions options;
    CHECK_OK(google::protobuf::util::MessageToJsonString(*message, &json_data,
                                                         options));
    std::ofstream file(output_filename.data(),
                       std::ios::out | std::ios::binary);
    if (!file) {
      LOG(FATAL) << "Failed to open output file [" << output_filename << "]";
    }
    file << json_data;
    CHECK(file.good());
  }
}

bool MatchesKeyType(absl::string_view key_type) {
  std::string flag = absl::GetFlag(FLAGS_key_type);
  // cl/362169587 accidentally changed the meaning of key_type to include
  // _t on numeric types, check for that for backward compatibility.
  if (flag.length() > 2 && flag.substr(flag.length() - 2, 2) == "_t") {
    flag = flag.substr(0, flag.length() - 2);
  }
  return flag == key_type;
}

template <typename T>
AbstractEncoder* CreateEncoder(absl::string_view key_type) {
  return MatchesKeyType(key_type) ? new IntegerEncoder<T> : nullptr;
}

