#ifndef THIRD_PARTY_GLOOP_UTIL_MEMORY_MEMORY_MAPPED_IO_TEST_DATA_H_
#define THIRD_PARTY_GLOOP_UTIL_MEMORY_MEMORY_MAPPED_IO_TEST_DATA_H_

#include <stddef.h>

#include <cstdint>

class ACMRandom;

namespace memory_mapped_io_test {

// Generates an array of random data using ACMRandom.
class TestData {
 public:
  TestData();
  ~TestData();

  // Allocate arrays and generate random data.
  // Three arrays are allocated...
  //   random_data_ : random data generated using ACMRandom
  //   write_data_  : initialized with a copy of the random_data_ array
  //   read_data_   : initialized to zeros
  void Initialize(const uint32_t random_seed, const size_t size_bytes);

  // Determine whether random data has been generated.
  bool IsInitialized() const;

  // Deallocate arrays and reset the class to it's newly constructed state.
  void Terminate();

  // Generate a random offset and size within the bounds of the test data.
  // Such that...
  // 0 < offset        <  data_size - min_size
  // 0 < offset + size <= data_size
  void RandomOffsetSize(ACMRandom& random, const size_t min_size,
                        size_t* const offset, size_t* const size);

  // Get a pointer to the constant random data generated by Initialize().
  const uint8_t* random_data() const {
    return reinterpret_cast<uint8_t*>(random_data_);
  }

  // Get a pointer to the array of initially zero'd data generated by
  // Initialize().
  uint8_t* write_data() const {
    return reinterpret_cast<uint8_t*>(write_data_);
  }

  // Get a pointer to the array of initially random data generated by
  // Initialize().
  uint8_t* read_data() const { return reinterpret_cast<uint8_t*>(read_data_); }

  // Get the size of each array - random_data(), write_data(), read_data() -
  // in bytes.
  size_t data_size_bytes() const { return data_size_bytes_; }

 protected:
  // Reset all members.
  void Reset();

  uint32_t* random_data_;
  uint32_t* write_data_;
  uint32_t* read_data_;
  size_t data_size_bytes_;
};

// Writes TestData to the specified file and deletes the file on destruction.
class TestDataFile {
 public:
  TestDataFile();
  // If a test file has been written it's deleted.
  ~TestDataFile();

  // Writes padding bytes of zeros at the start of test_filename followed by
  // random data from test_data.
  bool Write(const char* const test_filename, const TestData& test_data,
             const size_t padding_bytes);

  // Determines whether a data file was written by this object.
  bool HasFile() const;

  // Deletes the file written by this object.
  void Delete();

  // Retrieves the filename of the file this object previous wrote using
  // Write().
  const char* filename() const { return filename_; }

 protected:
  const char* filename_;
};

}  // namespace memory_mapped_io_test

#endif  // THIRD_PARTY_GLOOP_UTIL_MEMORY_MEMORY_MAPPED_IO_TEST_DATA_H_
