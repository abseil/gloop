TEST(MTRandomTest, Regression_CloseStringsAreDifferent) {
  const int kCount = 1000;

  // Two seeds differ only by the last character.
  MTRandom a(pseed + "1");
  MTRandom b(pseed + "2");

  absl::btree_set<uint32_t> first;
  absl::btree_set<uint32_t> all;
  for (int i = 0; i < kCount; ++i) {
    uint32_t v = a.Rand32();
    first.insert(v);
    all.insert(v);
    all.insert(b.Rand32());
  }

  // Broken array initialization implementation (before 2009-08-18) using the
  // above seeds return <1000, 1007>, generating output that is >99% similar.
  // The fix returns <1000, 2000> for completely disjoint sets.
  EXPECT_EQ(kCount, first.size());
  EXPECT_EQ(2 * kCount, all.size());
}

