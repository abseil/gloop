// Verifies that, after calling Reset() with a uint32, the RNG behaves
// the same as one that had been freshly constructed with the same value.
TEST(MTRandomTest, ResetUint32) {
  const uint32_t kSeed = 12345u;
  MTRandom gen1(kSeed);
  MTRandom gen2;
  gen2.Rand32();
  gen2.Reset(kSeed);
  for (int i = 0; i < 10; ++i) {
    uint32_t r1 = gen1.Rand32();
    uint32_t r2 = gen2.Rand32();
    EXPECT_EQ(r1, r2) << i;
  }
}

