// NOTE: skewed_low_distribution is not guaranteed to be stable.
TEST(SkewedLowDistributionTypeTest, StabilityTest) {
  using testing::ElementsAre;
  // skewed_low_distribution stability relies on
  // absl::random_internal::LeadingSetBit, std::log, std::pow.
  absl::random_internal::sequence_urbg urbg(
      {0x0003eb76f6f7f755ull, 0xFFCEA50FDB2F953Bull, 0xC332DDEFBE6C5AA5ull,
       0x6558218568AB9702ull, 0x2AEF7DAD5B6E2F84ull, 0x1521B62829076170ull,
       0xECDD4775619F1510ull, 0x13CCA830EB61BD96ull, 0x0334FE1EAA0363CFull,
       0xB5735C904C70A239ull, 0xD59E9E0BCBAADE14ull, 0xEECC86BC60622CA7ull});

  std::vector<int> output(6);

  {
    skewed_low_distribution<int32_t> dist(0, 256);
    std::generate(std::begin(output), std::end(output),
                  [&] { return dist(urbg); });
    EXPECT_THAT(output, ElementsAre(220, 2, 0, 6, 57, 39));
  }
  urbg.reset();
  {
    skewed_low_distribution<int32_t> dist(0, 256, 10);
    std::generate(std::begin(output), std::end(output),
                  [&] { return dist(urbg); });
    EXPECT_THAT(output, ElementsAre(8, 4, 0, 0, 0, 66));
  }
}

template <typename Engine, typename T>
void BM_SkewedLow3(benchmark::State& state) {
  volatile T kMin = 0;
  volatile T kMax = std::numeric_limits<T>::max() / 64 + 1;
  volatile T kBase = 3;

  Engine rng;
  skewed_low_distribution<T> dis(kMin, kMax, kBase);
  for (auto _ : state) {
    benchmark::DoNotOptimize(dis(rng));
  }
  state.SetBytesProcessed(
      sizeof(typename skewed_low_distribution<T>::result_type) *
      state.iterations());
}

BENCHMARK_TEMPLATE(BM_SkewedLow3, absl::InsecureBitGen, int32_t);
BENCHMARK_TEMPLATE(BM_SkewedLow3, absl::BitGen, int32_t);
BENCHMARK_TEMPLATE(BM_SkewedLow3, absl::InsecureBitGen, int64_t);
BENCHMARK_TEMPLATE(BM_SkewedLow3, absl::BitGen, int64_t);

