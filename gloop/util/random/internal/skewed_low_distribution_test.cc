template <typename IntType>
class SkewedLowDistributionTypeTest : public ::testing::Test {};

using IntTypes = ::testing::Types<int8_t, int16_t, int32_t, int64_t,  //
                                  uint8_t, uint16_t, uint32_t, uint64_t>;
TYPED_TEST_SUITE(SkewedLowDistributionTypeTest, IntTypes);

TYPED_TEST(SkewedLowDistributionTypeTest, SerializeTest) {
  using param_type = typename skewed_low_distribution<TypeParam>::param_type;
  using Limits = std::numeric_limits<TypeParam>;

  constexpr int kCount = 1000;
  absl::InsecureBitGen gen;
  for (const auto& param : {
           param_type(0, 1),                             //
           param_type(0, 2),                             //
           param_type(0, 2, 10),                         //
           param_type(9, 32, 4),                         //
           param_type(1, 101, 10),                       //
           param_type(1, Limits::max() / 2),             //
           param_type(0, Limits::max() - 1),             //
           param_type(0, Limits::max(), 2),              //
           param_type(0, Limits::max(), 10),             //
           param_type(Limits::min(), 0),                 //
           param_type(Limits::lowest(), Limits::max()),  //
           param_type(Limits::min(), Limits::max()),     //
       }) {
    // Validate parameters.
    const auto min = param.min();
    const auto max = param.max();
    const auto base = param.base();
    skewed_low_distribution<TypeParam> before(min, max, base);
    EXPECT_EQ(before.min(), param.min());
    EXPECT_EQ(before.max(), param.max());
    EXPECT_EQ(before.base(), param.base());

    {
      skewed_low_distribution<TypeParam> via_param(param);
      EXPECT_EQ(via_param, before);
    }

    // Validate stream serialization.
    std::stringstream ss;
    ss << before;

    skewed_low_distribution<TypeParam> after(3, 6, 17);

    EXPECT_NE(before.max(), after.max());
    EXPECT_NE(before.base(), after.base());
    EXPECT_NE(before.param(), after.param());
    EXPECT_NE(before, after);

    ss >> after;

    EXPECT_EQ(before.min(), after.min());
    EXPECT_EQ(before.max(), after.max());
    EXPECT_EQ(before.base(), after.base());
    EXPECT_EQ(before.param(), after.param());
    EXPECT_EQ(before, after);

    // Smoke test.
    auto sample_min = after.max();
    auto sample_max = after.min();
    for (int i = 0; i < kCount; i++) {
      auto sample = after(gen);
      EXPECT_GE(sample, after.min());
      EXPECT_LE(sample, after.max());
      if (sample > sample_max) sample_max = sample;
      if (sample < sample_min) sample_min = sample;
    }
    LOG(INFO) << "Range: " << sample_min << ", " << sample_max;
  }
}

using skewed_i32 = skewed_low_distribution<int32_t>;

class SkewedLowChiSquaredTest
    : public testing::TestWithParam<skewed_i32::param_type> {
 public:
  // The ChiSquaredTestImpl provides a chi-squared goodness of fit test for
  // data generated by the skewed-low distribution.
  double ChiSquaredTestImpl();

  // We use a fixed bit generator for distribution accuracy tests.  This allows
  // these tests to be deterministic, while still testing the qualify of the
  // implementation.
  absl::random_internal::pcg64_2018_engine rng_{0x2B7E151628AED2A6};
};

double SkewedLowChiSquaredTest::ChiSquaredTestImpl() {
  using absl::random_internal::kChiSquared;

  const auto& param = GetParam();

  // Check the distribution of L=floor(log(skewed_low_distribution, base)),
  // Expect that L is distributed such that:
  //   P[L=-1] > P[L=0] > P[L=1] > ... > P[L=max_log]
  //   k = sum(1..max_log)
  //   P[L=x] = (max_log - x) / k
  //
  const bool is_2 = (param.base() == 2);
  const double base_log = 1.0 / std::log(param.base());
  const auto bucket_index = [base_log, is_2, &param](int32_t x) {
    uint64_t y = static_cast<uint64_t>(x) - param.min();
    return (y == 0) ? 0
           : is_2   ? static_cast<int>(std::log2(y))
                    : static_cast<int>(std::log(y) * base_log);
  };
  const int max_bucket = bucket_index(param.max());

  // Based on the number of buckets, compute the number of trials to generate
  // such that the smallest bucket has about 6, and the expected values for each
  // of the buckets.
  const double total =
      static_cast<double>(max_bucket + 1 * (max_bucket + 2)) / 2.0;
  const size_t trials = static_cast<size_t>(6.0 / 1.0 / total);
  std::vector<double> expected(max_bucket + 1, 0);
  for (int i = 0; i < expected.size(); ++i) {
    expected[i] = expected.size() - i;
  }

  for (auto& e : expected) {
    e = (e / total) * trials;
  }

  skewed_i32 dist(param);
  std::vector<int64_t> buckets(max_bucket + 1);
  for (size_t i = 0; i < trials; ++i) {
    const auto sample = dist(rng_);
    // Check the bounds.
    ABSL_ASSERT(sample <= dist.max());
    ABSL_ASSERT(sample >= dist.min());
    // Convert the output of the generator to one of num_bucket buckets.
    int bucket = bucket_index(sample);
    ABSL_ASSERT(bucket <= max_bucket);
    ++buckets[bucket];
  }

  // Null-hypothesis is that the distribution is uniform with respect to
  // the skewed-low bucketization.
  const int dof = buckets.size() - 1;

  // The threshold for logging is 1-in-50.
  const double threshold = absl::random_internal::ChiSquareValue(dof, 0.98);

  double chi_square = absl::random_internal::ChiSquare(
      std::begin(buckets), std::end(buckets), std::begin(expected),
      std::end(expected));

  const double p = absl::random_internal::ChiSquarePValue(chi_square, dof);

  if (chi_square > threshold) {
    LOG(INFO) << "values";
    for (size_t i = 0; i < buckets.size(); i++) {
      LOG(INFO) << i << ": " << buckets[i] << " vs E " << expected[i];
    }
    LOG(INFO) << "trials=" << trials << "\n"
              << kChiSquared << "(data, " << dof << ") = " << chi_square << " ("
              << p << ")\n"
              << kChiSquared << " @ 0.98 = " << threshold;
  }

  return p;
}

TEST_P(SkewedLowChiSquaredTest, MultiTest) {
  const int kTrials = 5;

  int failures = 0;
  for (int i = 0; i < kTrials; i++) {
    double p_value = ChiSquaredTestImpl();
    if (p_value < 0.005) {  // 1/200
      failures++;
    }
  }

  // Run this test about 100 times (5 * 20 params), only 1 in 200 should fail,
  // so this should not be too flaky.
  EXPECT_LE(failures, 1);
}

