// The "constructor" for a CRC with a default polynomial.
CRC* CRC::Default(int degree, size_t roll_length) {
  ABSL_RAW_CHECK(8 <= degree && degree <= 128, "precondition");
  return crc_internal::MakeDefault(degree, &crc_internal::poly_list[degree],
                                   roll_length);
}

// The "constructor" for a CRC with a standard polynomial.
CRC* CRC::Standard(CRC::CRCName name, size_t roll_length) {
  int i = 0;
  while (i != ABSL_ARRAYSIZE(crc_internal::standard_poly_list) &&
         name != crc_internal::standard_poly_list[i].name) {
    i++;
  }
  ABSL_RAW_CHECK(i != ABSL_ARRAYSIZE(crc_internal::standard_poly_list),
                 "CRC implementation doesn't know CRC name");
  return crc_internal::MakeDefault(ABSL_ARRAYSIZE(crc_internal::poly_list) + i,
                                   &crc_internal::standard_poly_list[i].poly,
                                   roll_length);
}

// The "constructor" for a CRC with an arbitrary polynomial.
CRC* CRC::New(uint64_t lo, uint64_t hi, int degree, size_t roll_length) {
  return crc_internal::CRCImpl::NewInternal(lo, hi, degree, roll_length);
}

// This Concat implementation works for arbitrary polynomials.
void CRC::Concat(uint64_t* pxlo, uint64_t* pxhi, uint64_t ylo, uint64_t yhi,
                 int64_t ylen) {
  // https://en.wikipedia.org/wiki/Mathematics_of_cyclic_redundancy_checks
  // The CRC of a message M is the remainder of polynomial divison modulo G,
  // where the coefficient arithmetic is performed modulo 2 (so +/- are XOR):
  //   R(x) = M(x) x**n (mod G)
  // (n is the degree of G)
  // In practice, we use an initial value A and a bitmask B to get
  //   R = (A ^ B)x**|M| ^ Mx**n ^ B (mod G)
  // If M is the concatenation of two strings S and T, and Z is the string of
  // len(T) 0s, then the remainder CRC(ST) can be expressed as:
  //   R = (A ^ B)x**|ST| ^ STx**n ^ B
  //     = (A ^ B)x**|SZ| ^ SZx**n ^ B ^ Tx**n
  //     = CRC(SZ) ^ Tx**n
  // CRC(Z) = (A ^ B)x**|T| ^ B
  // CRC(T) = (A ^ B)x**|T| ^ Tx**n ^ B
  // So R = CRC(SZ) ^ CRC(Z) ^ CRC(T)
  //
  // And further, since CRC(SZ) = Extend(CRC(S), Z),
  //  CRC(SZ) ^ CRC(Z) = Extend(CRC(S) ^ CRC(''), Z).
  uint64_t zlo, zhi;
  uint64_t tlo, thi;
  Empty(&zlo, &zhi);
  tlo = *pxlo ^ zlo;
  thi = *pxhi ^ zhi;
  ExtendByZeroes(&tlo, &thi, ylen);
  *pxlo = tlo ^ ylo;
  *pxhi = thi ^ yhi;
}
