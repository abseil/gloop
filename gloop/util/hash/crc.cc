void CRC32::ExtendByZeroes(uint64_t* lo, uint64_t* hi, int64_t length) const {
  // Process the low order SMALL_BITS of the length by simply
  // using Extend() on an array of bytes that are zero.
  int small_part = (length & ((kOneInt64 << SMALL_BITS) - 1));
  if (small_part != 0) {
    this->Extend(lo, hi, zeroes, small_part);
  }
  length >>= SMALL_BITS;
  if (length != 0) {  // if the length was at least 2**SMALL_BITS
    uint32_t l = static_cast<uint32_t>(*lo);
    // For each ZEROES_BASE_LG bits in length
    // (after the low-order bits have been removed)
    // we lookup the appropriate polynomial in the zeroes_ array
    // and do a polynomial long multiplication (mod the CRC polynomial)
    // to extend the CRC by the appropriate number of bits.
    for (int i = 0; length != 0;
         i += ZEROES_BASE - 1, length >>= ZEROES_BASE_LG) {
      int c = length & (ZEROES_BASE - 1);  // pick next ZEROES_BASE_LG bits
      if (c != 0) {                        // if they are not zero,
                                           // multiply by entry in table
        // See comment in CRC64 describing the method.
        uint64_t m = this->zeroes_[c + i - 1];
        m <<= 1;
        uint64_t m2 = m << 1;
        uint64_t mtab[4] = {0, m, m2, m2 ^ m};
        l <<= (8 - (this->degree_ & 7)) & 7;
        uint64_t result = 0;
        for (int x = 0; x < this->degree_; x += 8) {
          result ^= mtab[l & 3] ^ (mtab[(l >> 2) & 3] << 2) ^
                    (mtab[(l >> 4) & 3] << 4) ^ (mtab[(l >> 6) & 3] << 6);
          l >>= 8;
          result = (result >> 8) ^ this->table0_[result & 0xff];
        }
        l = static_cast<uint32_t>(result);
      }
    }
    *lo = l;
  }
}

