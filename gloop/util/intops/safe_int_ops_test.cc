template <typename ClassType>
class SafeIntOpsTest : public ::testing::Test {
 protected:
  template <typename T>
  void TestAllTypes(char, std::vector<uint64_t>, std::vector<uint64_t>, T) {}
};

// Include all the basic types.
typedef ::testing::Types<int8_t, uint8_t, int16_t, uint16_t, int32_t, uint32_t,
                         int64_t, uint64_t>
    AllBasicTypes;

TYPED_TEST_SUITE(SafeIntOpsTest, AllBasicTypes);

TYPED_TEST(SafeIntOpsTest, TestAdd) {
  TypeParam result = 0;
  this->TestAllTypes('+', bit_patterns, bit_patterns, result);
}

TYPED_TEST(SafeIntOpsTest, TestSubtract) {
  TypeParam result = 0;
  this->TestAllTypes('-', bit_patterns, bit_patterns, result);
}

TYPED_TEST(SafeIntOpsTest, TestMultiply) {
  TypeParam result = 0;
  this->TestAllTypes('*', bit_patterns, bit_patterns, result);
}

TYPED_TEST(SafeIntOpsTest, TestDivide) {
  TypeParam result = 0;
  this->TestAllTypes('/', bit_patterns, bit_patterns, result);
}

TYPED_TEST(SafeIntOpsTest, TestMod) {
  TypeParam result = 0;
  this->TestAllTypes('%', bit_patterns, bit_patterns, result);
}

TYPED_TEST(SafeIntOpsTest, TestRightShift) {
  TypeParam result = 0;
  this->TestAllTypes('>', bit_patterns, shift_values, result);
}

TYPED_TEST(SafeIntOpsTest, TestLeftShift) {
  TypeParam result = 0;
  this->TestAllTypes('<', bit_patterns, shift_values, result);
}

